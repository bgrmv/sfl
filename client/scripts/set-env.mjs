// Writes src/environments/api-url.generated.ts from APP_ENV and API_URL.
// local (default) uses the dev server from the README; every other environment
// takes API_URL, or the same origin (`/rest`) when it is not set.
import { writeFileSync } from 'node:fs';

const ENVS = ['local', 'preview', 'staging', 'production'];
const LOCAL_API_URL = 'https://sfl.com:3001/rest';

const appEnv = process.env.APP_ENV || 'local';
if (!ENVS.includes(appEnv)) {
  console.error(`APP_ENV="${appEnv}" is unknown, expected one of: ${ENVS.join(', ')}`);
  process.exit(1);
}

const apiUrl = process.env.API_URL || (appEnv === 'local' ? LOCAL_API_URL : '/rest');

writeFileSync(
  new URL('../src/environments/api-url.generated.ts', import.meta.url),
  `// Generated by scripts/set-env.mjs, do not edit or commit\nexport const APP_ENV = '${appEnv}';\nexport const API_URL = '${apiUrl}';\n`,
);
console.log(`environment: ${appEnv}, apiUrl: ${apiUrl}`);
