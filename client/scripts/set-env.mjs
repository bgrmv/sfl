// Writes src/environments/api-url.generated.ts from APP_ENV and API_URL, and
// src/environments/build-info.generated.ts (version, commit, date; ADR 0022),
// releases.generated.ts and assets/releases.xml (RSS) from docs/releases.
// local (default) uses the dev server from the README; every other environment
// takes API_URL, or the same origin (`/rest`) when it is not set.
import { writeFileSync } from 'node:fs';
import { buildInfoSource, readBuildInfo } from './build-info.mjs';
import { loadReleases, releasesSource, rssFeed } from './releases.mjs';

const ENVS = ['local', 'preview', 'staging', 'production'];
const LOCAL_API_URL = 'https://sfl.com:3001/rest';

const appEnv = process.env.APP_ENV || 'local';
if (!ENVS.includes(appEnv)) {
  console.error(
    `APP_ENV="${appEnv}" is unknown, expected one of: ${ENVS.join(', ')}`,
  );
  process.exit(1);
}

const apiUrl =
  process.env.API_URL || (appEnv === 'local' ? LOCAL_API_URL : '/rest');

writeFileSync(
  new URL('../src/environments/api-url.generated.ts', import.meta.url),
  `// Generated by scripts/set-env.mjs, do not edit or commit\nexport const APP_ENV = '${appEnv}';\nexport const API_URL = '${apiUrl}';\n`,
);
console.log(`environment: ${appEnv}, apiUrl: ${apiUrl}`);

const buildInfo = readBuildInfo();
writeFileSync(
  new URL('../src/environments/build-info.generated.ts', import.meta.url),
  buildInfoSource(buildInfo),
);
console.log(`build: ${buildInfo.version} (${buildInfo.commit})`);

// Release notes: docs/releases -> page data and RSS (S10.51, ADR 0022)
const siteUrl = (process.env.SITE_URL || 'http://localhost:4200').replace(
  /\/$/,
  '',
);
const notes = loadReleases(
  new URL('../../docs/releases', import.meta.url).pathname,
);
writeFileSync(
  new URL('../src/environments/releases.generated.ts', import.meta.url),
  releasesSource(notes),
);
writeFileSync(
  new URL('../src/assets/releases.xml', import.meta.url),
  rssFeed({ releases: notes.releases, siteUrl }),
);
console.log(
  `releases: ${notes.releases.length}, early stages: ${notes.early.length}`,
);
