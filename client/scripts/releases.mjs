// docs/releases/X.Y.Z.md and EARLY-HISTORY.md -> data of the Release notes page and an RSS feed
// (S10.51, ADR 0022). Everything is read at build time: the page has no backend.
import { existsSync, readdirSync, readFileSync } from 'node:fs';

export const KINDS = ['New', 'Improved', 'Fixed', 'Under the hood'];
export const AREAS = [
  'Statistics',
  'Admin',
  'Players',
  'Community',
  'Design',
  'Access',
];

const CHANGE = /^- \*\*([^*]+)\*\*\s*(?:\(([^)]*)\)\s*)?(.*)$/;
const STORY = /\s*\[(S\d+\.\d+)\]\([^)]*\)\s*$/;

export function parseChange(line) {
  const match = CHANGE.exec(line.trim());
  if (!match) return undefined;
  const [, kind, area, rest] = match;
  if (!KINDS.includes(kind))
    throw new Error(`kind "${kind}" is unknown: ${KINDS.join(', ')}`);
  if (area !== undefined && !AREAS.includes(area)) {
    throw new Error(`area "${area}" is unknown: ${AREAS.join(', ')}`);
  }
  const story = STORY.exec(rest)?.[1];
  return { kind, area, text: rest.replace(STORY, '').trim(), story };
}

const changesOf = text => text.split('\n').map(parseChange).filter(Boolean);

export function parseRelease(text, fileName) {
  const parts = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(text);
  if (!parts) throw new Error(`${fileName}: no front matter`);
  const field = name =>
    new RegExp(`^${name}:[ \\t]*(.*)$`, 'm').exec(parts[1])?.[1].trim();
  const [version, date, title] = [
    field('version'),
    field('date'),
    field('title'),
  ];
  if (version !== fileName.replace(/\.md$/, '')) {
    throw new Error(
      `${fileName}: version "${version}" differs from the file name, expected ${fileName.replace(/\.md$/, '')}`,
    );
  }
  if (!date || !/^\d{4}-\d{2}-\d{2}$/.test(date))
    throw new Error(`${fileName}: date is not YYYY-MM-DD`);
  if (!title) throw new Error(`${fileName}: no title`);
  const changes = changesOf(parts[2]);
  if (changes.length === 0) throw new Error(`${fileName}: no changes`);
  return { version, date, title, changes };
}

const semverParts = v => v.split('.').map(Number);

export function sortReleases(releases) {
  return [...releases].sort((a, b) => {
    const [x, y] = [semverParts(a.version), semverParts(b.version)];
    return y[0] - x[0] || y[1] - x[1] || y[2] - x[2];
  });
}

export function parseEarlyHistory(text) {
  return text
    .split(/^## Early history · /m)
    .slice(1)
    .map(section => {
      const [head, ...body] = section.split('\n');
      const [date, ...title] = head.split(' · ');
      const lead = body
        .filter(l => l.trim() && !l.startsWith('-') && !l.startsWith('#'))
        .join(' ')
        .trim();
      return {
        date: date.trim(),
        title: title.join(' · ').trim(),
        lead,
        changes: changesOf(body.join('\n')),
      };
    });
}

export function loadReleases(dir) {
  const files = readdirSync(dir).filter(f => /^\d+\.\d+\.\d+\.md$/.test(f));
  const releases = sortReleases(
    files.map(f => parseRelease(readFileSync(`${dir}/${f}`, 'utf8'), f)),
  );
  const earlyFile = `${dir}/EARLY-HISTORY.md`;
  const early = existsSync(earlyFile)
    ? parseEarlyHistory(readFileSync(earlyFile, 'utf8'))
    : [];
  return { releases, early };
}

export const releasesSource = data =>
  `// Generated by scripts/set-env.mjs from docs/releases, do not edit or commit\nexport const RELEASES_DATA = ${JSON.stringify(data, null, 2)};\n`;

const escapeXml = s =>
  s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

export function rssFeed({ releases, siteUrl }) {
  const items = releases
    .map(r => {
      const list = r.changes
        .map(
          c =>
            `<li>${escapeXml(c.kind)}${c.area ? ` (${escapeXml(c.area)})` : ''}: ${escapeXml(c.text)}</li>`,
        )
        .join('');
      return `    <item>
      <title>${escapeXml(`${r.version} — ${r.title}`)}</title>
      <link>${siteUrl}/releases</link>
      <guid isPermaLink="false">sfl-release-${r.version}</guid>
      <pubDate>${new Date(`${r.date}T00:00:00Z`).toUTCString()}</pubDate>
      <description>${escapeXml(`<ul>${list}</ul>`)}</description>
    </item>`;
    })
    .join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0">
  <channel>
    <title>SFL release notes</title>
    <link>${siteUrl}/releases</link>
    <description>What changed on the site of the Saturday Football League</description>
${items}
  </channel>
</rss>
`;
}
