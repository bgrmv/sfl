// What the build knows about itself (ADR 0022): the version of the whole product is
// the `version` of the root package.json; the client and the server stay at 0.0.0.
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';

const SEMVER = /^\d+\.\d+\.\d+$/;

const rootPackage = new URL('../../package.json', import.meta.url);

export const readRootVersion = () =>
  JSON.parse(readFileSync(rootPackage, 'utf8')).version;

export const gitCommit = () =>
  execFileSync('git', ['rev-parse', '--short', 'HEAD'], {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'ignore'],
  }).trim();

export function readBuildInfo({
  readRootVersion: readVersion = readRootVersion,
  gitCommit: readCommit = gitCommit,
  now = new Date(),
} = {}) {
  const version = readVersion();
  if (!version) {
    throw new Error('the root package.json has no "version" (ADR 0022)');
  }
  if (!SEMVER.test(version)) {
    throw new Error(`root version "${version}" is not semver X.Y.Z (ADR 0022)`);
  }
  let commit;
  try {
    commit = readCommit();
  } catch {
    commit = 'unknown';
  }
  return { version, commit, builtAt: now.toISOString() };
}

export const buildInfoSource = ({ version, commit, builtAt }) =>
  `// Generated by scripts/set-env.mjs, do not edit or commit\nexport const BUILD_INFO = {\n  version: '${version}',\n  commit: '${commit}',\n  builtAt: '${builtAt}',\n};\n`;
